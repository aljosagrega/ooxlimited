<script>
(function () {
	'use strict';

	function slugify(text) {
		return text
			.toLowerCase()
			.trim()
			.replace(/[^\w\s-]/g, '')
			.replace(/[\s_-]+/g, '-')
			.replace(/^-+|-+$/g, '');
	}

	function buildNestedList(items) {
		var root = document.createElement('ul');
		var currentUl = root;
		var currentLi = null;
		var prevLevel = items[0].level;
		var ulStack = [root];

		items.forEach(function (item, index) {
			var level = item.level;

			if (index > 0) {
				if (level > prevLevel) {
					var depth = level - prevLevel;
					for (var d = 0; d < depth; d += 1) {
						var nestedUl = document.createElement('ul');
						if (currentLi) {
							currentLi.appendChild(nestedUl);
						}
						ulStack.push(nestedUl);
						currentUl = nestedUl;
					}
				} else if (level < prevLevel) {
					var steps = prevLevel - level;
					for (var s = 0; s < steps; s += 1) {
						ulStack.pop();
					}
					currentUl = ulStack[ulStack.length - 1];
				}
			}

			var li = document.createElement('li');
			var a = document.createElement('a');
			a.href = '#' + item.id;
			a.textContent = item.text;
			li.appendChild(a);
			currentUl.appendChild(li);
			currentLi = li;
			prevLevel = level;
		});

		return root;
	}

	function buildToc() {
		var main = document.querySelector('#main.site-main');
		var tocWrap = document.querySelector('.oox-toc');
		var tocNav = document.getElementById('oox-toc-list');

		if (!main || !tocWrap || !tocNav) {
			return;
		}

		var headings = main.querySelectorAll('h2, h3, h4, h5, h6');
		if (!headings.length) {
			tocWrap.hidden = true;
			return;
		}

		var usedIds = {};
		var items = [];

		headings.forEach(function (heading) {
			var text = heading.textContent.replace(/\s+/g, ' ').trim();
			if (!text) {
				return;
			}

			var id = heading.id;
			if (!id) {
				var base = slugify(text) || 'section';
				id = base;
				var n = 2;
				while (usedIds[id] || document.getElementById(id)) {
					id = base + '-' + n;
					n += 1;
				}
				heading.id = id;
			}

			usedIds[id] = true;

			items.push({
				level: parseInt(heading.tagName.slice(1), 10),
				text: text,
				id: id,
			});
		});

		if (!items.length) {
			tocWrap.hidden = true;
			return;
		}

		tocNav.innerHTML = '';
		tocNav.appendChild(buildNestedList(items));
		tocWrap.hidden = false;
	}

	function scheduleBuild() {
		buildToc();
	}

	if (document.readyState === 'loading') {
		document.addEventListener('DOMContentLoaded', scheduleBuild);
	} else {
		scheduleBuild();
	}

	window.addEventListener('load', scheduleBuild);

	if (window.elementorFrontend && window.elementorFrontend.hooks) {
		window.elementorFrontend.hooks.addAction('frontend/element_ready/global', scheduleBuild);
	}
})();
</script>
